import numpy as np, mpmath as mp
f32=np.float32
def F(x): return np.float32(x)
def fma(a,b,c): return np.float32(np.float64(a)*np.float64(b)+np.float64(c))
def mul(a,b): return np.float32(np.float64(a)*np.float64(b))
def add(a,b): return np.float32(np.float64(a)+np.float64(b))
def sub(a,b): return np.float32(np.float64(a)-np.float64(b))
def div(a,b): return np.float32(np.float64(a)/np.float64(b))
S1=F(-1.6666667163e-01);S2=F(8.3333337680e-03);S3=F(-1.9841270114e-04)
S4=F(2.7557314297e-06);S5=F(-2.5050759689e-08);S6=F(1.5896910177e-10)
C1=F(4.1666667908e-02);C2=F(-1.3888889225e-03);C3=F(2.4801587642e-05)
C4=F(-2.7557314297e-07);C5=F(2.0875723372e-09);C6=F(-1.1359647598e-11)
def ksin_dd(u,e):
    zh=mul(u,u); zl=fma(u,u,-zh)
    v=mul(zh,u); ve=fma(zh,u,-v); ve=fma(zl,u,ve)
    R=fma(zh,S6,F(S5)); R=fma(zh,R,F(S4)); R=fma(zh,R,F(S3)); R=fma(zh,R,F(S2)); R=fma(zh,R,F(S1))
    C=mul(v,R); Ce=fma(v,R,-C); Ce=fma(ve,R,Ce)
    s1=add(e,C); v1=sub(s1,e)
    s1e=add(sub(e,sub(s1,v1)),sub(C,v1))
    s=add(u,s1); se=add(sub(u,s),s1)
    return s, add(add(se,s1e),Ce)
def kcos_dd(u,e):
    zh=mul(u,u); zl=fma(u,u,-zh)
    P=fma(zh,F(C6),F(C5)); P=fma(zh,P,F(C4)); P=fma(zh,P,F(C3)); P=fma(zh,P,F(C2)); P=fma(zh,P,F(C1))
    zr=mul(zh,mul(zh,P))
    t=sub(zr,mul(u,e))
    hz=mul(zh,F(-0.5)); p=add(hz,F(1.0)); pe=sub(hz,sub(p,F(1.0)))
    c=sub(t,mul(zl,F(0.5)))
    return p, add(c,pe)
def tan_dd(u,e):
    sh,sl=ksin_dd(u,e); ch,cl=kcos_dd(u,e)
    q=div(sh,ch)
    e1=sub(sh,mul(q,ch))
    rem=add(e1,sl); rem=sub(rem,mul(q,cl))
    corr=div(rem,ch)
    return add(q,corr)
