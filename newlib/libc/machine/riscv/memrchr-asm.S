/* memrchr, backward m8 strip, vcpop hit resolution
   RVV 1.0, VLEN-agnostic (validated at VLEN 128/256/512).
   Generated by candidates/tools/gen.py
   (recommended variant: memrchr/rev).
*/
#include <sys/asm.h>

#if defined(__riscv_vector) && !defined(__riscv_e)

ENTRY(memrchr)
	andi	a1, a1, 0xff
	beqz	a2, .Lnull
	add	a0, a0, a2		/* a0 = one past the end */
	lbu	t0, -1(a0)
	beq	t0, a1, .Llast		/* need at the very end */
	li	t0, SZREG
	bltu	a2, t0, .Lbytes
	vsetvli	a3, a2, e8, m8, ta, ma	/* a3 = min(n, VLMAX) */
	bltu	a2, a3, .Ltail
.Lstrip:
	sub	a0, a0, a3
	vle8.v	v8, (a0)
	vmseq.vx v0, v8, a1
	vfirst.m a4, v0
	bltz	a4, .Lnext
	vcpop.m	a5, v0
	li	t1, 1
	bne	a5, t1, .Lslow		/* several hits: exact re-scan */
	add	a0, a0, a4
	ret
.Lnext:
	sub	a2, a2, a3
	bgeu	a2, a3, .Lstrip
	beqz	a2, .Lnull
.Ltail:
	vsetvli	a3, a2, e8, m8, ta, ma
	sub	a0, a0, a3
	vle8.v	v8, (a0)
	vmseq.vx v0, v8, a1
	vfirst.m a4, v0
	bltz	a4, .Lnull
	vcpop.m	a5, v0
	li	t1, 1
	bne	a5, t1, .Lslow
	add	a0, a0, a4
	ret
.Lslow:				/* >1 hit in this strip: scan it backwards */
	add	t1, a0, a3
1:	addi	t1, t1, -1
	lbu	t2, 0(t1)
	beq	t2, a1, .Lhit
	bne	t1, a0, 1b
.Lnull:
	li	a0, 0
	ret
.Lhit:
	mv	a0, t1
	ret
.Lbytes:				/* 1 <= n < SZREG */
	mv	t1, a0
	sub	a3, a0, a2
1:	addi	t1, t1, -1
	lbu	t2, 0(t1)
	beq	t2, a1, .Lhit
	bgtu	t1, a3, 1b
	j	.Lnull
.Llast:
	addi	a0, a0, -1
	ret
END(memrchr)
#endif
