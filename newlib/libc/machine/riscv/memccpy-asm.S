/* memccpy, RVV m8, 2-way
   RVV 1.0, VLEN-agnostic (validated at VLEN 128/256/512).
   Generated by candidates/tools/gen.py
   (recommended variant: memccpy/u2).
*/
#include <sys/asm.h>

#if defined(__riscv_vector) && !defined(__riscv_e) \
    && !defined(__OPTIMIZE_SIZE__) && !defined(PREFER_SIZE_OVER_SPEED)

ENTRY(memccpy)
	beqz	a3, .Lnull
	andi	a2, a2, 0xff
	mv	t0, a0			/* running dst */
	mv	t1, a1			/* running src */
	vsetvli	t2, a3, e8, m8, ta, ma	/* t2 = min(n, VLMAX) */
	bltu	a3, t2, .Lone
	slli	t3, t2, 1
	add	t4, t1, t2
	add	t5, t0, t2		/* dst + VLMAX */
	bltu	a3, t3, .Lstrip
.Lloop:
	vle8.v	v0, (t1)
	vle8.v	v8, (t4)
	vmseq.vx	v16, v0, a2
	vmseq.vx	v17, v8, a2
	vmor.mm	v18, v16, v17
	vfirst.m	a4, v18
	bgez	a4, .Lfound2
	vse8.v	v0, (t0)
	vse8.v	v8, (t5)
	add	t1, t1, t3
	add	t0, t0, t3
	add	t4, t4, t3
	add	t5, t5, t3
	sub	a3, a3, t3
	bgeu	a3, t3, .Lloop
.Lstrip:
	beqz	a3, .Lnull
	bltu	a3, t2, .Ltail
	vle8.v	v0, (t1)
	vmseq.vx	v16, v0, a2
	vfirst.m	a4, v16
	bgez	a4, .Lfound0
	vse8.v	v0, (t0)
	add	t1, t1, t2
	add	t0, t0, t2
	sub	a3, a3, t2
	j	.Lstrip
.Ltail:
	vsetvli	t2, a3, e8, m8, ta, ma
	vle8.v	v0, (t1)
	vmseq.vx	v16, v0, a2
	vfirst.m	a4, v16
	bltz	a4, .Lcopyall
.Lfound0:
	addi	a4, a4, 1
	vsetvli	zero, a4, e8, m8, ta, ma
	vse8.v	v0, (t0)
	add	a0, t0, a4
	ret
.Lcopyall:
	vse8.v	v0, (t0)
	j	.Lnull
.Lone:
	vle8.v	v0, (t1)
	vmseq.vx	v16, v0, a2
	vfirst.m	a4, v16
	bltz	a4, .Lcopyall
	j	.Lfound0
.Lnull:
	li	a0, 0
	ret
.Lfound2:
	/* A mask register holds only VLMAX bits, so v18 is the OR of the
	   two strips lane by lane, not their concatenation: the index from
	   vfirst.m v18 only says that some strip has a hit.  Resolve the
	   lower strip first, then the upper one.  */
	vfirst.m	a4, v16		/* hit in the lower strip? */
	bgez	a4, .Lfound0		/* yes: store a4+1 bytes there */
	vse8.v	v0, (t0)		/* whole lower strip: no hit in it */
	vfirst.m	a4, v17		/* hit index inside the upper strip */
	addi	a4, a4, 1		/* bytes to store in the upper strip */
	vsetvli	zero, a4, e8, m8, ta, ma
	vse8.v	v8, (t5)
	add	a0, t5, a4
	ret
END(memccpy)
#endif
